// lib/roles.js — นิยามบทบาทผู้ใช้ 4 ระดับ (ใช้ร่วมกันทั้ง server และหน้าเว็บ)
//
//   admin   ผู้ดูแลระบบ      — ทำได้ทุกอย่าง รวมถึงจัดการผู้ใช้/บริการ/ค่าตั้ง/ดู audit
//   sale    ฝ่ายขาย          — งานคิวพื้นฐาน + งานตัวแทน (รับคิวเป็นชุด/นำเข้าไฟล์/master data)
//   cs      ฝ่ายบริการลูกค้า — งานคิวพื้นฐาน: ดู/จัดการคิว รับ walk-in โทรยืนยัน จัดนัดหมาย
//   agency  ตัวแทน           — เห็นเฉพาะคิวของตัวเอง + สร้างคิวใหม่ได้ทางเดียว
//                             (แก้/ลบ/ยกเลิกไม่ได้ ดูรายงาน-ผู้ใช้-ค่าตั้งไม่ได้)
//
// "งานคิวพื้นฐาน" (ล็อกอินเข้ามาแล้วทำได้ทันที admin/sale/cs): ดูตารางคิว ค้นหา
// เปลี่ยนสถานะ/เลื่อนนัด รับคิว walk-in แท็บนัดที่กำลังจะถึง คำขอรอนัดหมาย
// เฉพาะ admin: รายงาน (report.view) · ประวัติการใช้งาน (logs.view) · จัดการบริการ (services.manage)
// ============================================================
"use strict";

const ROLES = {
  admin: { label: "ผู้ดูแลระบบ", perms: ["*"] },
  sale: { label: "ฝ่ายขาย", perms: ["agency.manage"] },
  cs: { label: "ฝ่ายบริการลูกค้า", perms: [] },
  agency: { label: "ตัวแทน", perms: [] },
};

// ระบบเดิมมี role "counter" — ให้เทียบเท่ากับ "cs" (migrate ตอนโหลดข้อมูลที่ store.js)
const normRole = (r) => (r === "counter" ? "cs" : ROLES[r] ? r : null);

// ตรวจสิทธิ์: can(role, "agency.manage") เป็นต้น — role ที่ไม่รู้จัก = ไม่มีสิทธิ์พิเศษ
function can(role, perm) {
  const r = ROLES[normRole(role)];
  return !!r && (r.perms.includes("*") || r.perms.includes(perm));
}

module.exports = { ROLES, normRole, can };
